package codegen

import (
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"
)

// helpersGo is a hand-written file in go/db/ that codegen must never touch.
const helpersGo = "package db\n\n// Helpers wraps the sqlc queries.\nfunc Helpers() {}\n"

// sqlcProject writes a project with one migration and the given query files,
// and runs the sqlc step once so go/db/ holds sqlc's output.
func sqlcProject(t *testing.T, queries map[string]string) {
	t.Helper()
	t.Chdir(t.TempDir())
	files := map[string]string{
		"go/db/migrations/0001_init.sql": "CREATE TABLE t (id int);\nCREATE TABLE u (id int);\n",
		"go/db/helpers.go":               helpersGo,
	}
	for name, sql := range queries {
		files["go/db/queries/"+name] = sql
	}
	writeFiles(t, files)
	emptyInputs = nil
	if err := runSQLC(nil); err != nil {
		t.Fatal(err)
	}
}

// goFilesIn lists the *.go files at the top level of dir, sorted.
func goFilesIn(t *testing.T, dir string) []string {
	t.Helper()
	matches, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		t.Fatal(err)
	}
	var names []string
	for _, m := range matches {
		names = append(names, filepath.Base(m))
	}
	slices.Sort(names)
	return names
}

func TestSQLCLastQueryDeletedRemovesOutput(t *testing.T) {
	sqlcProject(t, map[string]string{"t.sql": "-- name: ListT :many\nSELECT * FROM t;\n"})
	if got, want := goFilesIn(t, "go/db"), []string{"db.gen.go", "helpers.go", "models.gen.go", "t.sql.gen.go"}; !slices.Equal(got, want) {
		t.Fatalf("go/db after first run = %v, want %v", got, want)
	}

	if err := os.Remove("go/db/queries/t.sql"); err != nil {
		t.Fatal(err)
	}
	emptyInputs = nil
	if err := runSQLC(nil); err != nil {
		t.Fatal(err)
	}

	if got, want := goFilesIn(t, "go/db"), []string{"helpers.go"}; !slices.Equal(got, want) {
		t.Errorf("go/db after last query deleted = %v, want %v", got, want)
	}
	if got := readFile(t, "go/db/helpers.go"); got != helpersGo {
		t.Errorf("hand-written helpers.go changed:\n%s", got)
	}
	if want := []string{"no queries in go/db/queries — no query code generated"}; !slices.Equal(emptyInputs, want) {
		t.Errorf("empty inputs = %q, want %q", emptyInputs, want)
	}
	files := map[string]string{"main.go": mainStub}
	for _, name := range goFilesIn(t, "go/db") {
		files["db/"+name] = readFile(t, "go/db/"+name)
	}
	compileGenerated(t, files)
}

func TestSQLCOneQueryFileDeletedRemovesItsOutput(t *testing.T) {
	sqlcProject(t, map[string]string{
		"t.sql": "-- name: ListT :many\nSELECT * FROM t;\n",
		"u.sql": "-- name: ListU :many\nSELECT * FROM u;\n",
	})
	if got, want := goFilesIn(t, "go/db"), []string{"db.gen.go", "helpers.go", "models.gen.go", "t.sql.gen.go", "u.sql.gen.go"}; !slices.Equal(got, want) {
		t.Fatalf("go/db after first run = %v, want %v", got, want)
	}
	// Mark the surviving output, to see that it is regenerated.
	writeFiles(t, map[string]string{"go/db/t.sql.gen.go": "// Code generated by sqlc. DO NOT EDIT.\n\npackage db\n// marker\n"})

	if err := os.Remove("go/db/queries/u.sql"); err != nil {
		t.Fatal(err)
	}
	emptyInputs = nil
	if err := runSQLC(nil); err != nil {
		t.Fatal(err)
	}

	if got, want := goFilesIn(t, "go/db"), []string{"db.gen.go", "helpers.go", "models.gen.go", "t.sql.gen.go"}; !slices.Equal(got, want) {
		t.Errorf("go/db after u.sql deleted = %v, want %v", got, want)
	}
	if got := readFile(t, "go/db/t.sql.gen.go"); !strings.Contains(got, "func (q *Queries) ListT(") {
		t.Errorf("t.sql.gen.go not regenerated:\n%s", got)
	}
	if len(emptyInputs) != 0 {
		t.Errorf("empty inputs = %q, want none", emptyInputs)
	}
}

// Only sqlc's generated-code header marks a file as sqlc output: neither a
// mention of sqlc nor another generator's header does.
func TestSQLCKeepsFilesWithoutSQLCHeader(t *testing.T) {
	kept := map[string]string{
		"go/db/mentions.go":       "package db\n\n// Wraps the queries sqlc generates. Code generated by sqlc is never edited.\n",
		"go/db/late.go":           "package db\n\n// Package db\n//\n//\n//\n// Code generated by sqlc. DO NOT EDIT.\n",
		"go/db/migrations.gen.go": "// Code generated by schemaf. DO NOT EDIT.\n\npackage db\n",
		"go/db/notes.txt":         "sqlc output lives here\n",
	}
	sqlcProject(t, map[string]string{"t.sql": "-- name: ListT :many\nSELECT * FROM t;\n"})
	writeFiles(t, kept)
	if err := os.Remove("go/db/queries/t.sql"); err != nil {
		t.Fatal(err)
	}
	emptyInputs = nil
	if err := runSQLC(nil); err != nil {
		t.Fatal(err)
	}
	for path, want := range kept {
		if got := readFile(t, path); got != want {
			t.Errorf("%s removed or changed, got:\n%s", path, got)
		}
	}
}

// Every file sqlc writes follows the .gen. infix convention (CLAUDE.md ›
// Normative Conventions).
func TestSQLCOutputUsesGenInfix(t *testing.T) {
	sqlcProject(t, map[string]string{"t.sql": "-- name: ListT :many\nSELECT * FROM t;\n"})
	written, err := sqlcOutputFiles(dbDir)
	if err != nil {
		t.Fatal(err)
	}
	if len(written) == 0 {
		t.Fatal("sqlc wrote nothing")
	}
	for _, name := range written {
		if !strings.HasSuffix(name, ".gen.go") {
			t.Errorf("sqlc wrote %s, want a *.gen.go name", name)
		}
	}
}

// Upgrading from sqlc's default names: the old files are removed as stale
// on the first codegen, and the .gen.go files replace them.
func TestSQLCRemovesOutputUnderDefaultNames(t *testing.T) {
	sqlcProject(t, map[string]string{"t.sql": "-- name: ListT :many\nSELECT * FROM t;\n"})
	old := "// Code generated by sqlc. DO NOT EDIT.\n\npackage db\n"
	writeFiles(t, map[string]string{"go/db/db.go": old, "go/db/models.go": old, "go/db/t.sql.go": old})
	emptyInputs = nil
	if err := runSQLC(nil); err != nil {
		t.Fatal(err)
	}
	if got, want := goFilesIn(t, "go/db"), []string{"db.gen.go", "helpers.go", "models.gen.go", "t.sql.gen.go"}; !slices.Equal(got, want) {
		t.Errorf("go/db after upgrade = %v, want %v", got, want)
	}
}
