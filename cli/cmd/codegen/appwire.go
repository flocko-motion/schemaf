package codegen

import (
	"errors"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"strings"

	cli "github.com/flocko-motion/schemaf/cli"
	"strconv"
)

const (
	appDir     = "go/app"
	appWireGo  = "go/app/app.go"
	schemafPkg = "github.com/flocko-motion/schemaf/schemaf"
)

// checkAppWire fails unless go/app/app.go defines func Wire(app
// *schemaf.App), the app's wiring shared by main.go and the tests
// (EXTEND.md › App Wiring). There is no fallback to wiring in main.go.
func checkAppWire() error {
	fail := func(why string) error {
		return fmt.Errorf("%s %s: move your wiring from go/main.go into func Wire in go/app/app.go (EXTEND.md › App Wiring)", appWireGo, why)
	}
	f, err := parser.ParseFile(token.NewFileSet(), appWireGo, nil, parser.SkipObjectResolution)
	if err != nil {
		if isNotExist(err) {
			return fail("doesn't exist")
		}
		return fmt.Errorf("parsing %s: %w", appWireGo, err)
	}
	// The local name of the schemaf package in this file.
	local := ""
	for _, imp := range f.Imports {
		if path, _ := strconv.Unquote(imp.Path.Value); path == schemafPkg {
			local = "schemaf"
			if imp.Name != nil {
				local = imp.Name.Name
			}
		}
	}
	for _, d := range f.Decls {
		fn, ok := d.(*ast.FuncDecl)
		if !ok || fn.Recv != nil || fn.Name.Name != "Wire" {
			continue
		}
		if local != "" && fn.Type.Results == nil && isSchemafAppParam(fn.Type.Params, local) {
			return nil
		}
		return fail("has a func Wire, but not func Wire(app *schemaf.App)")
	}
	return fail("has no func Wire(app *schemaf.App)")
}

// isSchemafAppParam reports whether params is exactly one *<local>.App.
func isSchemafAppParam(params *ast.FieldList, local string) bool {
	if params == nil || len(params.List) != 1 || len(params.List[0].Names) > 1 {
		return false
	}
	star, ok := params.List[0].Type.(*ast.StarExpr)
	if !ok {
		return false
	}
	sel, ok := star.X.(*ast.SelectorExpr)
	if !ok {
		return false
	}
	id, ok := sel.X.(*ast.Ident)
	return ok && id.Name == local && sel.Sel.Name == "App"
}

func isNotExist(err error) bool { return errors.Is(err, fs.ErrNotExist) }

// schemafGenHeader starts every Go file schemaf codegen writes.
const schemafGenHeader = "// Code generated by schemaf codegen. DO NOT EDIT."

// removeLegacyAppFiles removes what codegen wrote into go/ before the
// constants and FrontendFS moved to go/app: go/constants.gen.go and
// go/frontend.gen.go (only with schemaf's generated header), and
// go/frontend_dist/ when it holds nothing but .gitkeep.
func removeLegacyAppFiles() error {
	for _, path := range []string{"go/constants.gen.go", "go/frontend.gen.go"} {
		b, err := os.ReadFile(path)
		if isNotExist(err) {
			continue
		}
		if err != nil {
			return err
		}
		if !strings.HasPrefix(string(b), schemafGenHeader) {
			continue
		}
		if err := os.Remove(path); err != nil {
			return fmt.Errorf("removing the old %s: %w", path, err)
		}
		cli.Info("removed the old %s (now in %s)", path, appDir)
	}
	entries, err := os.ReadDir("go/frontend_dist")
	if isNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	for _, e := range entries {
		if e.Name() != ".gitkeep" {
			return nil
		}
	}
	if err := os.RemoveAll("go/frontend_dist"); err != nil {
		return fmt.Errorf("removing the old go/frontend_dist: %w", err)
	}
	cli.Info("removed the old go/frontend_dist (now %s/frontend_dist)", appDir)
	return nil
}
