package codegen

import (
	cli "github.com/flocko-motion/schemaf/cli"
	"github.com/spf13/cobra"
)

// SubcommandProvider returns the codegen command. Codegen is fast, so it
// always runs every step; there are no single-step subcommands
// (EXTEND.md › Code Generation).
func SubcommandProvider(ctx *cli.Context) []*cobra.Command {
	run := func(cmd *cobra.Command, args []string) error { return runAll(ctx) }
	cmd := &cobra.Command{
		Use:   "codegen",
		Short: "Generate all code",
		Long: `Checks go/app/app.go defines func Wire, then generates everything: constants,
the frontend scaffold and FrontendFS, compose files and schemaf.sh, migrations,
sqlc queries, endpoints and the OpenAPI spec, the TypeScript and Go API
clients and the TypeScript test wrappers. Then it records the empty inputs
(gen/empty-inputs) and the inputs hash (gen/inputs.sha256).`,
		Args: cobra.NoArgs,
		PersistentPreRunE: func(cmd *cobra.Command, args []string) error {
			return chdirToProjectRoot()
		},
		RunE: run,
	}
	// The old spelling: schemaf.sh scripts generated by earlier versions call
	// "codegen all", e.g. right after upgrade.
	cmd.AddCommand(&cobra.Command{
		Use:    "all",
		Short:  "Same as codegen",
		Hidden: true,
		Args:   cobra.NoArgs,
		RunE:   run,
	})
	return []*cobra.Command{cmd}
}

// runAll runs every codegen step in order.
func runAll(ctx *cli.Context) error {
	emptyInputs = nil
	if err := checkAppWire(); err != nil {
		return err
	}
	if err := runConstantsGen(); err != nil {
		return err
	}
	if err := runScaffoldFrontend(); err != nil {
		return err
	}
	if err := runFrontendGen(); err != nil {
		return err
	}
	if err := runComposeGen(); err != nil {
		return err
	}
	if err := runMigrationsGen(ctx); err != nil {
		return err
	}
	if err := runSQLC(ctx); err != nil {
		return err
	}
	if err := runEndpointsGen(ctx); err != nil {
		return err
	}
	if err := runAPITS(); err != nil {
		return err
	}
	if err := runAPIGo(); err != nil {
		return err
	}
	if err := runTestsGen(); err != nil {
		return err
	}
	if err := runEmptyInputsGen(); err != nil {
		return err
	}
	return runInputsHashGen()
}
