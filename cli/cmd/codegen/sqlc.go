package codegen

import (
	"bufio"
	"bytes"
	_ "embed"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"text/template"

	sqllcpkg "github.com/sqlc-dev/sqlc/pkg/cli"
	cli "github.com/flocko-motion/schemaf/cli"
)

//go:embed sqlc.yaml.tmpl
var sqlcYAMLTemplate string

// Normative paths — not configurable.
const (
	dbDir         = "go/db"
	queriesDir    = dbDir + "/queries"
	migrationsDir = dbDir + "/migrations"
	sqlcYAMLPath  = dbDir + "/sqlc.yaml"
)

// sqlcHeader is the line sqlc writes at the top of every file it generates.
// Codegen identifies sqlc's output by this header only, never by name, so
// hand-written files in go/db/ are never touched.
const sqlcHeader = "// Code generated by sqlc. DO NOT EDIT."

// sqlcHeaderLines is how many leading lines may precede the header (sqlc
// can put build tags above it).
const sqlcHeaderLines = 5

func runSQLC(_ *cli.Context) error {
	// Ensure normative directories exist
	for _, dir := range []string{queriesDir, migrationsDir} {
		if err := os.MkdirAll(dir, 0755); err != nil {
			return fmt.Errorf("creating %s: %w", dir, err)
		}
	}

	// Codegen owns sqlc's output: remove it before every sqlc step, so output
	// whose query file is gone never survives (EXTEND.md › Queries).
	removed, err := removeSQLCOutput(dbDir)
	if err != nil {
		return err
	}

	// No queries: sqlc refuses an empty query set, so it doesn't run and
	// generates nothing (EXTEND.md › Empty inputs).
	hasQueries, err := hasSQLFiles(queriesDir)
	if err != nil {
		return err
	}
	if !hasQueries {
		reportStaleSQLCOutput(removed, nil)
		warnEmptyInput("no queries in %s — no query code generated", queriesDir)
		return nil
	}

	// Generate sqlc.yaml — package is always "db", output always goes to go/db/
	tmpl, err := template.New("sqlc").Parse(sqlcYAMLTemplate)
	if err != nil {
		return fmt.Errorf("parsing sqlc.yaml template: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, map[string]string{"Package": "db"}); err != nil {
		return fmt.Errorf("executing sqlc.yaml template: %w", err)
	}

	if err := os.WriteFile(sqlcYAMLPath, buf.Bytes(), 0644); err != nil {
		return fmt.Errorf("writing %s: %w", sqlcYAMLPath, err)
	}
	cli.Info("Generated %s", sqlcYAMLPath)

	// Run sqlc via embedded library — no external binary needed.
	// NOTE: sqlc resolves paths relative to the config file location (go/db/).
	if code := sqllcpkg.Run([]string{"generate", "--file", sqlcYAMLPath}); code != 0 {
		return fmt.Errorf("sqlc generate failed with exit code %d", code)
	}

	written, err := sqlcOutputFiles(dbDir)
	if err != nil {
		return err
	}
	reportStaleSQLCOutput(removed, written)
	cli.Success("sqlc generate completed → %s/ (%s)", dbDir, strings.Join(written, ", "))
	return nil
}

// removeSQLCOutput deletes every file at the top level of dir that carries
// sqlc's generated-code header, and returns their names.
func removeSQLCOutput(dir string) ([]string, error) {
	files, err := sqlcOutputFiles(dir)
	if err != nil {
		return nil, err
	}
	for _, name := range files {
		path := filepath.Join(dir, name)
		if err := os.Remove(path); err != nil {
			return nil, fmt.Errorf("removing sqlc output %s: %w", path, err)
		}
	}
	return files, nil
}

// reportStaleSQLCOutput prints each removed file that sqlc did not write
// again: its query file is gone, so its code is gone. Files sqlc rewrote are
// not stale and not reported.
func reportStaleSQLCOutput(removed, written []string) {
	for _, name := range removed {
		if !slices.Contains(written, name) {
			cli.Info("removed stale sqlc output: %s", filepath.Join(dbDir, name))
		}
	}
}

// sqlcOutputFiles lists the names of the files at the top level of dir that
// carry sqlc's generated-code header, sorted.
func sqlcOutputFiles(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("reading %s: %w", dir, err)
	}
	var names []string
	for _, e := range entries {
		if !e.Type().IsRegular() {
			continue
		}
		generated, err := hasSQLCHeader(filepath.Join(dir, e.Name()))
		if err != nil {
			return nil, err
		}
		if generated {
			names = append(names, e.Name())
		}
	}
	return names, nil
}

// hasSQLCHeader reports whether one of the first lines of the file is sqlc's
// generated-code header.
func hasSQLCHeader(path string) (bool, error) {
	f, err := os.Open(path)
	if err != nil {
		return false, fmt.Errorf("reading %s: %w", path, err)
	}
	defer f.Close()
	scanner := bufio.NewScanner(f)
	for i := 0; i < sqlcHeaderLines && scanner.Scan(); i++ {
		if strings.TrimRight(scanner.Text(), " \t\r") == sqlcHeader {
			return true, nil
		}
	}
	// A first line too long for the scanner can't be sqlc's header line.
	if err := scanner.Err(); err != nil && err != bufio.ErrTooLong {
		return false, fmt.Errorf("reading %s: %w", path, err)
	}
	return false, nil
}
