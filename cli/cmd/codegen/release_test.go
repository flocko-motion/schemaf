package codegen

// Tests for the generated release workflow (INSTALL.md › Releases from CI).
// The shell steps read their inputs from env only, so they run here with bash
// against a stubbed gh, without GitHub.

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	"gopkg.in/yaml.v3"
)

type workflow struct {
	On          map[string]any    `yaml:"on"`
	Permissions map[string]string `yaml:"permissions"`
	Concurrency map[string]any    `yaml:"concurrency"`
	Jobs        map[string]struct {
		RunsOn string            `yaml:"runs-on"`
		Env    map[string]string `yaml:"env"`
		Steps  []struct {
			ID   string            `yaml:"id"`
			Name string            `yaml:"name"`
			Uses string            `yaml:"uses"`
			Run  string            `yaml:"run"`
			Env  map[string]string `yaml:"env"`
			With map[string]string `yaml:"with"`
		} `yaml:"steps"`
	} `yaml:"jobs"`
}

// generateReleaseWorkflow runs codegen's release step in a minimal project and
// returns the file's text and its parsed form.
func generateReleaseWorkflow(t *testing.T) (string, workflow) {
	t.Helper()
	t.Chdir(t.TempDir())
	writeMinimalProject(t)
	if err := runReleaseGen(); err != nil {
		t.Fatal(err)
	}
	text := readFile(t, ".github/workflows/release.gen.yml")
	var wf workflow
	if err := yaml.Unmarshal([]byte(text), &wf); err != nil {
		t.Fatalf("release.gen.yml is not valid YAML: %v\n%s", err, text)
	}
	return text, wf
}

// stepScript returns the run script of the step with the given id.
func stepScript(t *testing.T, wf workflow, id string) string {
	t.Helper()
	for _, s := range wf.Jobs["release"].Steps {
		if s.ID == id {
			if s.Run == "" {
				t.Fatalf("step %q has no run script", id)
			}
			if strings.Contains(s.Run, "${{") {
				t.Errorf("step %q uses ${{ }} inside its script; pass values through env", id)
			}
			return s.Run
		}
	}
	t.Fatalf("no step with id %q", id)
	return ""
}

// fakeGh logs every call to $GH_LOG. `gh release view <tag>` succeeds when
// $GH_STATE/release-<tag> exists; `gh api` prints $GH_STATE/api.json;
// `gh release create` creates the release.
const fakeGh = `#!/bin/bash
echo "gh $*" >> "$GH_LOG"
case "$1 $2" in
  "release view") [ -f "$GH_STATE/release-$3" ] ; exit ;;
  "release create") touch "$GH_STATE/release-$3"; exit 0 ;;
  "release upload") [ "$3" != schemaf-index ] || cp "$4" "$GH_STATE/uploaded-releases.json"; exit 0 ;;
  "release edit") exit 0 ;;
esac
case "$1" in
  api) cat "$GH_STATE/api.json"; exit 0 ;;
esac
echo "fake gh: unhandled: $*" >&2; exit 1
`

type stepRun struct {
	dir, state, log, output string
}

// runStep runs a step script in fresh directories; see runStepIn.
func runStep(t *testing.T, wf workflow, id string, env map[string]string) (stepRun, string, error) {
	t.Helper()
	return runStepIn(t, wf, id, env, t.TempDir(), t.TempDir())
}

func TestReleaseWorkflowShape(t *testing.T) {
	text, wf := generateReleaseWorkflow(t)
	mustContain(t, "release.gen.yml", text, "# Code generated by schemaf codegen. DO NOT EDIT.")

	push, _ := wf.On["push"].(map[string]any)
	if tags, _ := push["tags"].([]any); len(tags) != 1 || tags[0] != "v*" {
		t.Errorf("on.push.tags = %v, want [v*]", push["tags"])
	}
	if len(wf.On) != 1 {
		t.Errorf("triggers = %v, want only push of tags", wf.On)
	}
	for k, v := range map[string]string{"contents": "write", "id-token": "write", "attestations": "write"} {
		if wf.Permissions[k] != v {
			t.Errorf("permissions.%s = %q, want %q", k, wf.Permissions[k], v)
		}
	}
	if wf.Concurrency["group"] == nil || wf.Concurrency["cancel-in-progress"] != false {
		t.Errorf("concurrency = %v, want one group that never cancels", wf.Concurrency)
	}
	job := wf.Jobs["release"]
	if job.RunsOn != "ubuntu-24.04" {
		t.Errorf("runs-on = %q", job.RunsOn)
	}
	if job.Env["NAME"] != "myapp" || job.Env["SCHEMAF_RUNTIME"] != "docker" {
		t.Errorf("job env = %v, want NAME=myapp, SCHEMAF_RUNTIME=docker", job.Env)
	}

	var build, attest string
	for _, s := range job.Steps {
		if s.Uses != "" && !strings.Contains(s.Uses, "@") {
			t.Errorf("action %q is not pinned", s.Uses)
		}
		if strings.HasPrefix(s.Uses, "actions/") && len(strings.SplitN(s.Uses, "@", 2)[1]) != 40 {
			t.Errorf("action %q is not pinned to a commit hash", s.Uses)
		}
		if strings.Contains(s.Run, "schemaf.sh build") {
			build = s.Run
		}
		if strings.HasPrefix(s.Uses, "actions/attest-build-provenance@") {
			attest = s.With["subject-path"]
		}
	}
	mustContain(t, "build step", build, `./schemaf.sh build --tag "$VERSION" --output "$ARTIFACT"`)
	if attest != "${{ steps.version.outputs.artifact }}" {
		t.Errorf("attestation subject = %q, want the artifact", attest)
	}
}

func TestReleaseWorkflowTag(t *testing.T) {
	_, wf := generateReleaseWorkflow(t)
	for tag, want := range map[string]string{
		"v1.4.0":         "version=1.4.0\nprerelease=false\nartifact=myapp-1.4.0.run\n",
		"v2.0.0-dev.3":   "version=2.0.0-dev.3\nprerelease=true\nartifact=myapp-2.0.0-dev.3.run\n",
		"v10.20.30-rc-1": "version=10.20.30-rc-1\nprerelease=true\nartifact=myapp-10.20.30-rc-1.run\n",
	} {
		r, out, err := runStep(t, wf, "version", map[string]string{"TAG": tag})
		if err != nil {
			t.Errorf("%s refused: %v\n%s", tag, err, out)
			continue
		}
		if got := readFile(t, r.output); got != want {
			t.Errorf("%s outputs:\n%s\nwant:\n%s", tag, got, want)
		}
	}
	for _, tag := range []string{"v1.4", "v1.4.0+build.7", "v01.2.3", "v1.2.3-", "v1.2.3-a_b", "vX.Y.Z", "v1.2.0-rc.", "v1.2.0-rc..1", "v1.2.0-.rc"} {
		_, out, err := runStep(t, wf, "version", map[string]string{"TAG": tag})
		if err == nil {
			t.Errorf("%s accepted", tag)
			continue
		}
		mustContain(t, tag, out, "::error::tag "+tag+" is not a release tag — use vX.Y.Z or vX.Y.Z-<pre>")
	}
}

func TestReleaseWorkflowPublish(t *testing.T) {
	_, wf := generateReleaseWorkflow(t)
	env := func(pre string) map[string]string {
		return map[string]string{"TAG": "v1.4.0", "PRERELEASE": pre, "ARTIFACT": "myapp-1.4.0.run", "BUNDLE_PATH": "bundle.json"}
	}
	t.Run("a new release is created with both files", func(t *testing.T) {
		r, out, err := runStepWithBundle(t, wf, env("false"), false)
		if err != nil {
			t.Fatalf("%v\n%s", err, out)
		}
		log := readFile(t, r.log)
		mustContain(t, "gh calls", log, "gh release create v1.4.0 --verify-tag --title v1.4.0 --generate-notes myapp-1.4.0.run myapp-1.4.0.run.sigstore.json")
		mustNotContain(t, "gh calls", log, "--prerelease")
		if readFile(t, filepath.Join(r.dir, "myapp-1.4.0.run.sigstore.json")) != "BUNDLE" {
			t.Error("bundle not saved as <artifact>.sigstore.json")
		}
	})

	t.Run("a prerelease is marked as one and never latest", func(t *testing.T) {
		r, out, err := runStepWithBundle(t, wf, env("true"), false)
		if err != nil {
			t.Fatalf("%v\n%s", err, out)
		}
		mustContain(t, "gh calls", readFile(t, r.log), "--prerelease --latest=false myapp-1.4.0.run")
	})

	t.Run("a release created by hand keeps its notes, gets the files", func(t *testing.T) {
		r, out, err := runStepWithBundle(t, wf, env("false"), true)
		if err != nil {
			t.Fatalf("%v\n%s", err, out)
		}
		log := readFile(t, r.log)
		mustContain(t, "gh calls", log,
			"gh release upload v1.4.0 myapp-1.4.0.run myapp-1.4.0.run.sigstore.json --clobber",
			"gh release edit v1.4.0 --prerelease=false")
		mustNotContain(t, "gh calls", log, "release create")
	})
}

// runStepWithBundle runs the publish step with an artifact and a bundle in its
// directory; exists says whether the tag's release already exists.
func runStepWithBundle(t *testing.T, wf workflow, env map[string]string, exists bool) (stepRun, string, error) {
	t.Helper()
	dir, state := t.TempDir(), t.TempDir()
	for name, content := range map[string]string{"myapp-1.4.0.run": "ART", "bundle.json": "BUNDLE"} {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0644); err != nil {
			t.Fatal(err)
		}
	}
	if exists {
		if err := os.WriteFile(filepath.Join(state, "release-v1.4.0"), nil, 0644); err != nil {
			t.Fatal(err)
		}
	}
	return runStepIn(t, wf, "publish", env, dir, state)
}

// runStepIn runs a step script with bash in dir, with the job's env plus env,
// a stubbed gh on PATH (state in state) and $GITHUB_OUTPUT.
func runStepIn(t *testing.T, wf workflow, id string, env map[string]string, dir, state string) (stepRun, string, error) {
	t.Helper()
	if _, err := exec.LookPath("jq"); err != nil {
		t.Skip("jq not installed")
	}
	r := stepRun{dir: dir, state: state, log: filepath.Join(state, "gh.log"), output: filepath.Join(state, "github_output")}
	bin := t.TempDir()
	if err := os.WriteFile(filepath.Join(bin, "gh"), []byte(fakeGh), 0755); err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command("bash", "-c", stepScript(t, wf, id))
	cmd.Dir = dir
	cmd.Env = []string{
		"PATH=" + bin + ":" + os.Getenv("PATH"),
		"GH_LOG=" + r.log, "GH_STATE=" + state, "GITHUB_OUTPUT=" + r.output,
		"NAME=myapp", "GH_REPO=acme/myapp",
	}
	for k, v := range env {
		cmd.Env = append(cmd.Env, k+"="+v)
	}
	out, err := cmd.CombinedOutput()
	return r, string(out), err
}

