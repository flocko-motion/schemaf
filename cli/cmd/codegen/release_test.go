func TestReleaseWorkflowIndex(t *testing.T) {
	_, wf := generateReleaseWorkflow(t)
	for _, exists := range []bool{false, true} {
		dir, state := t.TempDir(), t.TempDir()
		if err := os.WriteFile(filepath.Join(state, "api.json"), []byte(apiPages), 0644); err != nil {
			t.Fatal(err)
		}
		if exists {
			if err := os.WriteFile(filepath.Join(state, "release-schemaf-index"), nil, 0644); err != nil {
				t.Fatal(err)
			}
		}
		r, out, err := runStepIn(t, wf, "index", nil, dir, state)
		if err != nil {
			t.Fatalf("index step failed: %v\n%s", err, out)
		}
		// Only published releases with a release tag and both of this app's
		// files; prerelease from the version.
		if got := readFile(t, filepath.Join(state, "uploaded-releases.json")); got != wantIndex {
			t.Errorf("releases.json:\n%s\nwant:\n%s", got, wantIndex)
		}
		log := readFile(t, r.log)
		mustContain(t, "gh calls", log, "gh api --paginate repos/acme/myapp/releases?per_page=100", "gh release upload schemaf-index releases.json --clobber")
		if exists {
			mustNotContain(t, "gh calls", log, "release create")
		} else {
			mustContain(t, "gh calls", log, "gh release create schemaf-index --latest=false")
		}
	}
}

func TestReleaseWorkflowWarnsOutsideRepoRoot(t *testing.T) {
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git not installed")
	}
	repo := t.TempDir()
	git(t, repo, "init", "-q")
	proj := filepath.Join(repo, "myapp")
	if err := os.MkdirAll(proj, 0755); err != nil {
		t.Fatal(err)
	}
	t.Chdir(proj)
	writeMinimalProject(t)
	warning, err := releaseRootWarning()
	if err != nil {
		t.Fatal(err)
	}
	mustContain(t, "warning", warning, ".github/workflows/release.gen.yml is in ", "not at the repository root ", "GitHub won't run it")

	t.Chdir(repo)
	if w, err := releaseRootWarning(); err != nil || w != "" {
		t.Errorf("at the repository root: warning %q, err %v", w, err)
	}
	t.Chdir(t.TempDir())
	if w, err := releaseRootWarning(); err != nil || w != "" {
		t.Errorf("outside a repository: warning %q, err %v", w, err)
	}
}
